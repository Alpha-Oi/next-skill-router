/**
 * Минимальный набор стоп-слов (EN + RU), которые не несут смысла
 * в поисковом запросе и создают шум в BM25-матчинге.
 */
export const STOPWORDS = new Set([
  // English
  'a', 'an', 'the', 'this', 'that', 'these', 'those',
  'is', 'are', 'was', 'were', 'be', 'been', 'being', 'am',
  'have', 'has', 'had', 'do', 'does', 'did', 'doing',
  'will', 'would', 'could', 'should', 'may', 'might', 'must', 'can',
  'of', 'in', 'to', 'for', 'on', 'with', 'at', 'by', 'from', 'as',
  'or', 'and', 'but', 'if', 'so', 'no', 'not',
  'it', 'its', 'it\'s', 'i', 'me', 'my', 'we', 'our', 'you', 'your',
  'he', 'she', 'his', 'her', 'they', 'them', 'their',

  // Russian
  'и', 'в', 'во', 'не', 'что', 'он', 'на', 'я', 'с', 'со',
  'как', 'а', 'то', 'все', 'она', 'так', 'его', 'но', 'да',
  'к', 'у', 'же', 'вы', 'за', 'бы', 'по', 'ее', 'мне', 'было',
  'вот', 'от', 'меня', 'еще', 'нет', 'о', 'из', 'ему', 'теперь',
  'когда', 'даже', 'ну', 'ли', 'если', 'уже', 'или', 'ни',
  'мой', 'моя', 'моё', 'мои', 'это', 'этот', 'эта', 'эти',
  'быть', 'был', 'была', 'были', 'буду', 'будет', 'будут',
  'ты', 'твой', 'твоя', 'ваш', 'ваша', 'мы', 'нас', 'нам',
]);

/**
 * Убирает стоп-слова из текста запроса, сохраняя порядок остальных токенов.
 * Возвращает строку, готовую для передачи в MiniSearch.
 */
export function stripStopwords(text) {
  if (!text) return '';
  return text
    .split(/\s+/)
    .map((w) => w.replace(/^[^\p{L}\p{N}\[\]()_:-]+|[^\p{L}\p{N}\[\]()_:-]+$/gu, ''))
    .filter((w) => w.length > 0 && !STOPWORDS.has(w.toLowerCase()))
    .join(' ');
}
